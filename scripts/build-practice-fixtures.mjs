import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import {
  buildCertifiedPracticeFixturesForGeneration,
  compactPracticeFixtures
} from "../src/practice.js";
import { COMMITTED_COACHING_TECHNIQUES } from "../src/puzzles.js";

const outputFile = path.resolve("src/generated/practice-fixtures.js");
const fixtures = Object.fromEntries(COMMITTED_COACHING_TECHNIQUES.map((technique) => [
  technique,
  compactPracticeFixtures(buildCertifiedPracticeFixturesForGeneration(technique))
]));
const output = [
  "// Generated by `npm run practice:fixtures:build`. Do not edit by hand.",
  `export const PRECOMPUTED_PRACTICE_FIXTURES = ${JSON.stringify(fixtures)};`,
  ""
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(outputFile, "utf8");
  assert.equal(current, output, "Precomputed practice fixtures are stale. Run `npm run practice:fixtures:build`.");
  console.log(`Precomputed practice fixtures are current: ${countFixtures(fixtures)} fixtures.`);
} else {
  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, output);
  console.log(`Wrote ${countFixtures(fixtures)} precomputed practice fixtures to ${outputFile}.`);
}

function countFixtures(catalog) {
  return Object.values(catalog).reduce((sum, items) => sum + items.length, 0);
}
